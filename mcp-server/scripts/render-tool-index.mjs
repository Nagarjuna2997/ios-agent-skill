#!/usr/bin/env node
//
// render-tool-index.mjs — keep the "All registered tools" table in
// docs/mcp/tools.md identical to what the unified server actually registers.
//
//   node scripts/render-tool-index.mjs          rewrite the generated block
//   node scripts/render-tool-index.mjs --check  exit 1 if it is stale (CI)
//
// Run from mcp-server/ after `npm run build`. The table is generated from a
// live tools/list call, so a renamed, added or removed tool cannot silently
// leave the reference page behind.

import { readFile, writeFile } from "node:fs/promises";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const DOC = new URL("../../docs/mcp/tools.md", import.meta.url);
const START = "<!-- tool-index:start -->";
const END = "<!-- tool-index:end -->";

// Ordered groups: the first matching rule wins. Guides are relative to docs/mcp/.
const GROUPS = [
  { name: "iOS build agent", guide: "../tooling/ios-build-agent.md", test: (n) => /^ios_/.test(n) },
  { name: "Source reviews", guide: "#choosing-a-tool", test: (n) => /^(review_|analyze_|check_availability|audit_|lint_skill)/.test(n) && !/system_integrations|color_system|backend/.test(n) },
  { name: "Color and backend", guide: "../backend/overview.md", test: (n) => /color_system|backend_integration/.test(n) },
  { name: "Apple system integrations", guide: "../integrations/README.md", test: (n) => /system_integration|apple_permissions|apple_capabilities/.test(n) },
  { name: "Apple references and local library", guide: "knowledge-server.md", test: (n) => /^(search_apple|get_apple|plan_ios_app|plan_app_icon|search_local|read_local|get_reference)/.test(n) },
  { name: "Installed Apple documentation", guide: "../tooling/local-apple-documentation.md", test: (n) => /^(apple_docs_|xcode_mcp_)/.test(n) },
  { name: "Simulator and Xcode", guide: "../tooling/ios-simulator-mcp.md", test: (n) => /^(simulator_|install_app|launch_app|terminate_app|open_deep_link|screenshot$|build_project|run_tests)/.test(n) },
  { name: "Screenshot Studio", guide: "../screenshots/README.md", test: (n) => /screenshot/.test(n) },
  { name: "App creation", guide: "../tooling/project-scaffolding.md", test: (n) => n === "create_app" },
  { name: "Failure reports", guide: "../tooling/issue-reporting.md", test: (n) => /issue_report|private_feedback/.test(n) },
];

const sentences = (text = "") => text.replace(/\s+/g, " ").trim().match(/[^.!?]+[.!?]?(?=\s|$)/g) ?? [];
// Prefer the tool's title. Otherwise use the first descriptive sentence:
// "Use this to X" becomes "X"; "Use this when/before/after …" is skipped.
const purpose = (tool) => {
  if (tool.title) return tool.title.replace(/\|/g, "\\|");
  const parts = sentences(tool.description).map((s) => s.trim());
  let chosen = parts.find((s) => !/^Use (this|when)\b(?! to\b)/i.test(s) || /^Use this to\b/i.test(s)) ?? parts[0] ?? "";
  chosen = chosen.replace(/^Use this to (\w)/i, (_, c) => c.toUpperCase());
  return chosen.replace(/\|/g, "\\|");
};
const access = (tool) =>
  tool.annotations?.readOnlyHint === true ? "read-only" : tool.annotations?.readOnlyHint === false ? "writes or runs" : "not declared";

const client = new Client({ name: "tool-index", version: "1" });
let tools;
try {
  await client.connect(new StdioClientTransport({ command: process.execPath, args: ["dist/unified.js"] }));
  ({ tools } = await client.listTools());
} finally {
  await client.close();
}

const grouped = new Map(GROUPS.map((g) => [g, []]));
for (const tool of tools) {
  const group = GROUPS.find((g) => g.test(tool.name));
  if (!group) throw new Error(`No documentation group for tool ${tool.name}; add one to GROUPS.`);
  grouped.get(group).push(tool);
}

const lines = [
  START,
  "<!-- Generated by mcp-server/scripts/render-tool-index.mjs from a live tools/list call. Do not edit by hand. -->",
  "",
  `The unified \`ios-agent-mcp\` server registers ${tools.length} tools. "Access" repeats each tool's declared \`readOnlyHint\` annotation; "not declared" means the tool does not state it.`,
  "",
];
for (const [group, members] of grouped) {
  if (!members.length) continue;
  lines.push(`### ${group.name} (${members.length})`, "", `Guide: [${group.guide.startsWith("#") ? "this page" : group.guide}](${group.guide})`, "", "| Tool | Access | Purpose |", "|---|---|---|");
  for (const tool of members.sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`| \`${tool.name}\` | ${access(tool)} | ${purpose(tool)} |`);
  }
  lines.push("");
}
lines.push(END);
const block = lines.join("\n");

const current = await readFile(DOC, "utf8");
const pattern = new RegExp(`${START}[\\s\\S]*?${END}`);
if (!pattern.test(current)) throw new Error(`docs/mcp/tools.md is missing the ${START} … ${END} block`);
const next = current.replace(pattern, block);

if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("docs/mcp/tools.md tool index is stale. Run: cd mcp-server && npm run build && node scripts/render-tool-index.mjs");
    process.exit(1);
  }
  console.log(`OK - docs/mcp/tools.md lists all ${tools.length} registered tools`);
} else {
  await writeFile(DOC, next);
  console.log(`Wrote ${tools.length} tools to docs/mcp/tools.md`);
}

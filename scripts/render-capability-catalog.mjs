#!/usr/bin/env node
// Render capabilities/CATALOG.md (and the README capability summary) from
// capabilities/catalog.json and the module manifests, so status counts and the
// landscape cannot drift from what actually exists.
//
//   node scripts/render-capability-catalog.mjs          write
//   node scripts/render-capability-catalog.mjs --check  exit 1 when stale or inconsistent
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "capabilities");
const catalog = JSON.parse(readFileSync(join(dir, "catalog.json"), "utf8")).entries;
const modules = new Map();
for (const entry of readdirSync(dir, { withFileTypes: true })) {
  if (!entry.isDirectory() || entry.name.startsWith("_")) continue;
  const file = join(dir, entry.name, "manifest.json");
  if (existsSync(file)) modules.set(entry.name, JSON.parse(readFileSync(file, "utf8")));
}

const problems = [];
const byId = new Map(catalog.map((e) => [e.id, e]));
for (const [id, manifest] of modules) {
  const entry = byId.get(id);
  if (!entry) problems.push(`module ${id} is not listed in catalog.json`);
  else {
    if (entry.category !== manifest.category) problems.push(`module ${id} category ${manifest.category} differs from catalog ${entry.category}`);
    if (manifest.default && !entry.defaultInCategory) problems.push(`module ${id} is a category default but catalog.json does not mark it defaultInCategory`);
  }
  for (const alternative of manifest.alternatives ?? []) if (!byId.has(alternative)) problems.push(`module ${id} lists unknown alternative ${alternative}`);
  for (const doc of manifest.docs ?? []) if (!existsSync(join(root, doc))) problems.push(`module ${id} links missing doc ${doc}`);
}
for (const entry of catalog) for (const doc of entry.docs) if (!existsSync(join(root, doc))) problems.push(`catalog ${entry.id} links missing doc ${doc}`);

const status = (entry) => modules.get(entry.id)?.status ?? "planned";
const counts = { verified: 0, untested: 0, blocked: 0, planned: 0 };
for (const entry of catalog) counts[status(entry)]++;
const compiled = (entry) => {
  const check = modules.get(entry.id)?.compileCheck;
  return check?.result === "passed" ? `Xcode ${check.xcode}, ${check.date}` : "no";
};
const compiledCount = [...modules.values()].filter((m) => m.compileCheck?.result === "passed").length;
const priorities = ["P0", "P1", "P2", "P3"];
const categories = [...new Set(catalog.map((e) => e.category))];

const esc = (text) => String(text).replace(/\|/g, "\\|");
const lines = [
  "# Capability catalog",
  "",
  "<!-- Generated by scripts/render-capability-catalog.mjs from catalog.json and module manifests. Do not edit by hand. -->",
  "",
  `The landscape of capabilities an iOS app can need: ${catalog.length} entries in ${categories.length} categories. ${modules.size} have a module in this folder.`,
  "",
  `Status: **${counts.verified} verified**, **${counts.untested} untested**, **${counts.blocked} blocked**, **${counts.planned} planned** (no module yet).`,
  "",
  "- `verified`: the module's verify check built it into a minimal app on a Mac (see its `verification.json`).",
  "- `untested`: the module exists and the agent applies it, but its build check has not passed on a Mac yet.",
  "- `blocked`: the module cannot work in the current setup; see its manifest note.",
  "- `planned`: listed for planning and cost estimates only; the agent reports it as not built.",
  "",
  `Compiled: ${compiledCount} modules passed the combined compile check (every module's Swift and usage file built together in one app target on a Mac; see [README.md](README.md#compile-check)). That is evidence the code compiles, not a verified module: the per-module verify also covers the XcodeGen project, entitlements and extension targets.`,
  "",
  "Cost models describe how a service charges, not prices. No price in this catalog is claimed as current; module manifests carry an amount only when it was confirmed on the vendor page, with the date.",
  "",
  "| Priority | Entries | Modules |",
  "|---|---|---|",
  ...priorities.map((p) => `| ${p} | ${catalog.filter((e) => e.priority === p).length} | ${catalog.filter((e) => e.priority === p && modules.has(e.id)).length} |`),
  "",
];
for (const category of categories) {
  const entries = catalog.filter((e) => e.category === category).sort((a, b) => priorities.indexOf(a.priority) - priorities.indexOf(b.priority) || a.id.localeCompare(b.id));
  lines.push(`## ${category}`, "", "| Capability | Id | Kind | Cost model | You provide | Docs | Priority | Status | Compiled |", "|---|---|---|---|---|---|---|---|---|");
  for (const e of entries) {
    const kind = `${e.appleNative ? "Apple" : "third-party"}${e.defaultInCategory ? ", default" : ""}`;
    const docs = e.docs.map((d) => `[${d.split("/").pop().replace(/\.md$/, "")}](../${d})`).join(", ");
    const name = modules.has(e.id) ? `[${esc(e.name)}](${e.id}/recipe.md)` : esc(e.name);
    lines.push(`| ${name} | \`${e.id}\` | ${kind} | ${e.cost.model}: ${esc(e.cost.note)} | ${e.credentials.length ? e.credentials.map((c) => `\`${c}\``).join(", ") : "nothing"} | ${docs} | ${e.priority} | ${status(e)} | ${compiled(e)} |`);
  }
  lines.push("");
}
const catalogMarkdown = lines.join("\n");

const summary = [
  "<!-- capability-summary:start -->",
  `| Status | Capabilities |`,
  "|---|---|",
  `| Verified on a Mac | ${counts.verified} |`,
  `| Module exists, not yet verified on a Mac | ${counts.untested} |`,
  `| ...of which the Swift compiled on a Mac (combined compile check) | ${compiledCount} |`,
  `| Blocked | ${counts.blocked} |`,
  `| Listed for planning only | ${counts.planned} |`,
  "",
  `${catalog.length} catalog entries in ${categories.length} categories; generated from [capabilities/CATALOG.md](capabilities/CATALOG.md).`,
  "<!-- capability-summary:end -->",
].join("\n");

const readmePath = join(root, "README.md");
const readme = readFileSync(readmePath, "utf8");
const marker = /<!-- capability-summary:start -->[\s\S]*?<!-- capability-summary:end -->/;
const nextReadme = marker.test(readme) ? readme.replace(marker, summary) : readme;
const catalogPath = join(dir, "CATALOG.md");
const current = existsSync(catalogPath) ? readFileSync(catalogPath, "utf8") : "";

if (process.argv.includes("--check")) {
  if (problems.length) {
    console.error(`Capability catalog problems:\n${problems.join("\n")}`);
    process.exit(1);
  }
  if (current !== catalogMarkdown || nextReadme !== readme) {
    console.error("capabilities/CATALOG.md or the README capability summary is stale. Run: node scripts/render-capability-catalog.mjs");
    process.exit(1);
  }
  console.log(`OK - ${catalog.length} catalog entries, ${modules.size} modules (${counts.verified} verified, ${counts.untested} untested, ${counts.blocked} blocked)`);
} else {
  if (problems.length) console.warn(`Warnings:\n${problems.join("\n")}`);
  writeFileSync(catalogPath, catalogMarkdown);
  writeFileSync(readmePath, nextReadme);
  console.log(`Wrote CATALOG.md: ${catalog.length} entries, ${modules.size} modules`);
}
